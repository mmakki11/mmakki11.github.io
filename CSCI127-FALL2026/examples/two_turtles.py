#A program that uses multi-colored turtles
import turtle

azul = turtle.Turtle()
azul.color("blue")

verde = turtle.Turtle()
verde.color("green")

azul.forward(100)
azul.right(90)
azul.forward(50)

verde.right(90)
verde.forward(100)
verde.right(45)
verde.forward(75)
